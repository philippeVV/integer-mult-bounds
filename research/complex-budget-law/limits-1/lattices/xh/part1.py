"""expXH part 1: fixed-window E_n sublattices.  Roots of E_n (I_{n,1}, k=(3;1^n)), heights <= Hmax, restricted to
x mod 2 in a fixed binary code C of length n+1 (dim 8 or 9 -> h <= 9/10 automatically).  Valid sets = cliques of the
graph 'ip in {0,+-1}' (valuation lemma: W/2 exact under parity labels).  Max clique by greedy + CP-SAT; exact
evaluation of h, rank, coordinate-term cost and gamma.
usage: part1.py n Hmax family [cpsat_seconds]
families: e8pad (even-weight on coords 0..8), blocks (all block codes with 8/9 blocks, profiles), rand (random codes
generated by low-weight even words)."""
import sys, itertools, random
import numpy as np
import os as _os, sys as _sys; _sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))  # python -I omits the script dir
from enroots import en_roots
from lib import evaluate, max_clique

n, Hmax, fam = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
secs = float(sys.argv[4]) if len(sys.argv) > 4 else 20
R = en_roots(n, Hmax)
eps = np.array([-1] + [1] * n)
Rbits = (R % 2).astype(np.int64)
pw = (1 << np.arange(n + 1)).astype(np.int64)
Rint = Rbits @ pw
print(f"n={n} Hmax={Hmax} roots(lines)={len(R)}", flush=True)


EVS = []


def span_set(gens):
    S = {0}
    for g in gens:
        S |= {s ^ g for s in S}
    return S


def members(gens):
    S = span_set(gens)
    return np.array([int(v) in S for v in Rint])


def greedy(adj, restarts=30, seed=0):
    rng = random.Random(seed)
    V = len(adj); best = []
    deg = adj.sum(1)
    for t in range(restarts):
        order = sorted(range(V), key=lambda a: -deg[a] + rng.random() * (V if t else 0) * 0.02)
        cl = []
        ok = np.ones(V, dtype=bool)
        for a in order:
            if ok[a]:
                cl.append(a); ok &= adj[a]
        if len(cl) > len(best):
            best = cl
    return best


def run(name, gens):
    msk = members(gens)
    X = R[msk]
    if len(X) < 60:
        return None
    W = (X * eps) @ X.T
    adj = np.isin(W, (-1, 0, 1))
    np.fill_diagonal(adj, False)
    g = greedy(adj)
    res = (len(g), False, None)
    cl = g
    from lib import clique_ls
    if len(X) > 1500:
        ls = clique_ls(adj, iters=8000, restarts=2, init=g)
        ls2 = clique_ls(adj, iters=8000, restarts=1, seed=3)
        for c_ in (ls, ls2):
            if len(c_) > len(cl): cl = c_
        res = (len(cl), False, None)
    elif secs > 0:
        c2, opt, ub = max_clique(adj, seconds=secs, hint=g)
        if len(c2) >= len(cl):
            cl = c2
        res = (len(cl), opt, ub)
    ev = evaluate(X[cl], eps)
    EVS.append(ev)
    flag = ' <<< CANDIDATE' if (ev['h'] <= 10 and ev['V'] > 120 and ev['gamma'] < 4 / 7) else ''
    print(f"{name:40s} dimC={len(gens)} cand={len(X):6d} clique={res[0]:4d} opt={res[1]} ub={res[2]} | "
          f"V={ev['V']} h={ev['h']} rank={ev['rank']} C={ev['C']} gamma={ev['gamma']:.3f} merit={ev['merit']:.2f}{flag}",
          flush=True)
    return ev


if fam == 'e8pad':
    gens = [(1 << 0) | (1 << i) for i in range(1, 9)]
    run('even-weight on 0..8 (E8 + padding)', gens)
elif fam == 'blocks':
    N = n + 1
    seen = set()
    for nb in (8, 9):
        if nb > N: continue
        # partitions of N into nb positive parts (non-increasing)
        def parts(rem, k, mx):
            if k == 0:
                if rem == 0: yield []
                return
            for p in range(min(rem - (k - 1), mx), 0, -1):
                for rest in parts(rem - p, k - 1, p):
                    yield [p] + rest
        for prof in parts(N, nb, N):
            for z in sorted(set(prof)):          # size of block containing time coord 0
                key = (tuple(prof), z)
                if key in seen: continue
                seen.add(key)
                # build blocks: block with coord 0 has size z
                sizes = list(prof); sizes.remove(z); sizes = [z] + sizes
                coords = list(range(N)); blocks = []; pos = 0
                for s_ in sizes:
                    blocks.append(coords[pos:pos + s_]); pos += s_
                gens = [sum(1 << c for c in b) for b in blocks]
                run(f"blocks {sizes}", gens)
elif fam == 'rand':
    trials = int(sys.argv[5]) if len(sys.argv) > 5 else 50
    rng = random.Random(1)
    wts = [2, 4]
    for t in range(trials):
        gens = []
        while len(gens) < 8:
            w = rng.choice(wts)
            g = sum(1 << c for c in rng.sample(range(n + 1), w))
            if g not in span_set(gens):
                gens.append(g)
        run(f"rand{t}", gens)

# limits-1 replay: no valid set at h <= 10 exceeds 120 lines (stop test of expXA step 1)
assert all(not (e['h'] <= 10 and e['V'] > 120) for e in EVS)
print('PASS_EXPXH_PART1')
