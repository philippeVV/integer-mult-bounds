"""expXN: GRS-F2 screen of phase-model terminal-frame families on BH scenario A (157 sessions), m = 4..8.

Bound (expXJ Sec.2, proved): for any gate assignment G over a char-2 field on the incidence,
    s >= rank_{GF(2^16)} Z_G,  Z_G[j,k] = T_G[j,k] (I + beta_j + beta_k)   (beta_j := beta_in of session j).
Nullity 0 (for ONE G) is an exact certificate: s >= Wm for EVERY interior phase-frame assignment with
these terminal frames.  Each family is drawn once (fixed seed) and screened against 3 independent G.

usage: screen.py m [m ...]   -> screen_m<m>.json + stdout log
"""
import sys, os, json, time
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'expXJ'))
import grs2                                  # BH scenario A incidence, GF(2^16), Zmat, grank
bh = grs2.bh
B = list(bh.B); W = len(B)
SRC = [bh.sess_src[q] for q in B]; SNK = [bh.sess_snk[q] for q in B]
GSEEDS = (101, 102, 103)


# ---------------- F2 helpers ----------------
def rank2(A):
    A = A.copy() % 2; r = 0; n, c = A.shape
    for col in range(c):
        piv = np.nonzero(A[r:, col])[0]
        if len(piv) == 0: continue
        p = r + piv[0]; A[[r, p]] = A[[p, r]]
        rows = np.nonzero(A[:, col])[0]; rows = rows[rows != r]
        A[rows] ^= A[r]; r += 1
        if r == n: break
    return r


def rand_gl(rng, m):
    while True:
        g = rng.integers(0, 2, (m, m))
        if rank2(g) == m: return g


def alt_nondeg(rng, m):
    """random alternating form of rank 2*floor(m/2)."""
    J = np.zeros((m, m), dtype=np.int64)
    for i in range(0, m - 1, 2): J[i, i + 1] = J[i + 1, i] = 1
    g = rand_gl(rng, m)
    return (g.T @ J @ g) % 2


def odd_vec(rng, m):
    while True:
        u = rng.integers(0, 2, m)
        if u.sum() % 2: return u


def algebra_dim(mats, m, cap=40):
    """dim over F2 of the unital associative algebra generated by mats (cap on number of generators used)."""
    basis = []; piv = {}
    def add(M):
        v = (M.reshape(-1) % 2).copy()
        for p, b in piv.items():
            if v[p]: v ^= b
        nz = np.nonzero(v)[0]
        if len(nz) == 0: return False
        p = nz[0]
        for q in list(piv):
            if piv[q][p]: piv[q] ^= v
        piv[p] = v; basis.append(M % 2); return True
    gens = [np.eye(m, dtype=np.int64)] + list(mats[:cap])
    for g in gens: add(g)
    i = 0
    while i < len(basis) and len(basis) < m * m:
        for g in gens[1:]:
            add((basis[i] @ g) % 2)
            if len(basis) == m * m: break
        i += 1
    return len(basis)


# ---------------- F9 labels via a fixed F2-linear embedding of F9 = F3^2 ----------------
TRIT = {0: (0, 0), 1: (1, 0), 2: (0, 1)}       # F3 -> F2^2 (fixed injection)
def enc9(x):                                     # F9 element (a + 3b) -> 4 bits
    a, b = x % 3, x // 3
    return list(TRIT[a]) + list(TRIT[b])


def enc_vec(xs):
    return np.array([bit for x in xs for bit in enc9(x)], dtype=np.int64)


def families(m):
    rng = np.random.default_rng(1000 + m)
    E20 = rng.integers(0, 2, (m, 20))            # fixed F2-linear map F2^20 -> F2^m
    E12 = rng.integers(0, 2, (m, 12))
    E4 = rng.integers(0, 2, (m, 4))
    fold20 = np.zeros((m, 20), dtype=np.int64)
    for i in range(20): fold20[i % m, i] = 1
    F = {}
    def sym(rng_):
        A = rng_.integers(0, 2, (m, m)); return np.triu(A) + np.triu(A, 1).T
    F['random_sym'] = [sym(rng) for _ in range(W)]
    F['random_alt'] = [(lambda A: (A + A.T) % 2)(rng.integers(0, 2, (m, m))) for _ in range(W)]
    # (1) twin of expNY signed labels: beta_k = sum_{u in U_k} u u^T, U_k odd-weight pairwise-orthogonal,
    # sessions sharing a src or snk gate get mutually orthogonal U (greedy; conflicts counted)
    for r in sorted({1, max(1, m // 2)}):
        betas, conflicts = [], 0
        Us = []
        for k in range(W):
            nb = [Us[j] for j in range(k) if SRC[j] in (SRC[k], SNK[k]) or SNK[j] in (SRC[k], SNK[k])]
            best = None
            for _ in range(400):
                U = []
                for _ in range(400):
                    if len(U) == r: break
                    u = odd_vec(rng, m)
                    if all((u @ w) % 2 == 0 for w in U) and not any((u == w).all() for w in U): U.append(u)
                if len(U) < r: continue
                bad = sum(1 for V in nb for u in U for w in V if (u @ w) % 2)
                if best is None or bad < best[0]: best = (bad, U)
                if bad == 0: break
            conflicts += best[0] > 0; U = best[1]; Us.append(U)
            betas.append(sum(np.outer(u, u) for u in U) % 2)
        F[f'signed_orth_r{r}'] = betas
        F[f'signed_orth_r{r}_conflicts'] = conflicts
    # (2) symplectic / orthogonal structured
    F['alt_nondeg_orbit'] = [alt_nondeg(rng, m) for _ in range(W)]                       # GL-orbit of J (symplectic forms)
    J0 = alt_nondeg(np.random.default_rng(7), m)
    F['J_plus_diag'] = [(J0 + np.diag(rng.integers(0, 2, m))) % 2 for _ in range(W)]     # Z/4 refinements of one symplectic form
    F['gram_gl'] = [(lambda g: (g @ g.T) % 2)(rand_gl(rng, m)) for _ in range(W)]        # congruence orbit of I (orthogonal-type)
    D = np.diag([1, 1] + [0] * (m - 2))
    F['orbit_rank2'] = [(lambda g: (g.T @ D @ g) % 2)(rand_gl(rng, m)) for _ in range(W)]
    F['I_plus_wwT'] = [(np.eye(m, dtype=np.int64) + np.outer(w, w)) % 2 for w in (odd_vec(rng, m) for _ in range(W))]
    X0, Y0 = sym(np.random.default_rng(5)), sym(np.random.default_rng(6))
    F['two_class_noncomm_srcpar'] = [X0 if SRC[k] % 2 else Y0 for k in range(W)]
    F['two_class_noncomm_pointline'] = [X0 if SRC[k] < 91 else Y0 for k in range(W)]
    # (3) F9-label families (BH local code coordinates gen[(v,q)] in F9^5, PG(2,9) coords in F9^3)
    for ename, E in (('rand', E20), ('fold', fold20)):
        us = [(E @ enc_vec(bh.gen[(SRC[k], q)])) % 2 for k, q in enumerate(B)]
        ut = [(E @ enc_vec(bh.gen[(SNK[k], q)])) % 2 for k, q in enumerate(B)]
        F[f'f9gen_{ename}_uuT_src'] = [np.outer(u, u) % 2 for u in us]
        F[f'f9gen_{ename}_src+snk'] = [(np.outer(u, u) + np.outer(t, t)) % 2 for u, t in zip(us, ut)]
        F[f'f9gen_{ename}_cross'] = [(np.outer(u, t) + np.outer(t, u)) % 2 for u, t in zip(us, ut)]
        F[f'f9gen_{ename}_cross+diag'] = [(np.outer(u, t) + np.outer(t, u) + np.diag(u)) % 2 for u, t in zip(us, ut)]
    # five-column Gram of the source local-code row, each F9 entry -> F2^m by E4 (twin of five-subset labels)
    F['f9gen_gram5'] = [sum(np.outer(w, w) for w in ((E4 @ np.array(enc9(x))) % 2 for x in bh.gen[(SRC[k], q)])) % 2
                        for k, q in enumerate(B)]
    F['f9gen_gram5_srcsnk'] = [sum(np.outer(w1, w2) + np.outer(w2, w1) for w1, w2 in zip(
        ((E4 @ np.array(enc9(x))) % 2 for x in bh.gen[(SRC[k], q)]),
        ((E4 @ np.array(enc9(x))) % 2 for x in bh.gen[(SNK[k], q)]))) % 2 for k, q in enumerate(B)]
    def pg(v): return bh.T[v] if v < 91 else bh.T[v - 91]
    up = [(E12 @ enc_vec(pg(SRC[k]))) % 2 for k in range(W)]
    ul = [(E12 @ enc_vec(pg(SNK[k]))) % 2 for k in range(W)]
    F['pg_coords_src+snk'] = [(np.outer(a, a) + np.outer(b, b)) % 2 for a, b in zip(up, ul)]
    F['pg_coords_cross'] = [(np.outer(a, b) + np.outer(b, a) + np.eye(m, dtype=np.int64) * (k % 2)) % 2
                            for k, (a, b) in enumerate(zip(up, ul))]
    return F


def nullity(T, betas):
    m = betas[0].shape[0]
    return W * m - grs2.grank(grs2.Zmat(T, [b.astype(np.int64) for b in betas]))


if __name__ == '__main__':
    Ts = [grs2.transfer(np.random.default_rng(s)) for s in GSEEDS]
    for s, T in zip(GSEEDS, Ts):
        print(f"G seed {s}: rank T_G = {grs2.grank(T)} / {W}, nonzeros {int((T != 0).sum())}", flush=True)
    for m in map(int, sys.argv[1:]):
        F = families(m); res = {}
        for name, betas in F.items():
            if not isinstance(betas, list): res[name] = betas; continue
            ncomm = sum(1 for a, b in zip(betas[:-1], betas[1:]) if not ((a @ b - b @ a) % 2 == 0).all())
            adim = algebra_dim(betas, m)
            t = time.time()
            nl = [nullity(T, betas) for T in Ts]
            res[name] = {'nullity': nl, 'noncomm_adjacent_pairs': ncomm, 'alg_dim': adim, 'Wm': W * m}
            print(f"m={m} {name:32s} nullity {nl}  non-commuting adjacent pairs {ncomm}/{W-1}  "
                  f"dim alg = {adim}/{m*m}  ({time.time()-t:.0f}s)", flush=True)
        json.dump(res, open(os.path.join(HERE, f'screen_m{m}.json'), 'w'), indent=1)
