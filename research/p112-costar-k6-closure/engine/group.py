"""Stabilizer of the deleted frame F0 inside Aut(E8)/{+-1}, acting on the 120 lines.

Generators: reflections in frame roots, plus all products of two reflections that
preserve F0 as a set.  The group is enumerated element by element (BFS) to get its
exact order; frames of E8 are counted and the W(E8)-orbit of F0 is computed.
"""
import pickle, sys
import numpy as np
from model import L, N, F0, GM

KEY = {}
for i, v in enumerate(L):
    KEY[v] = i
    KEY[tuple(-x for x in v)] = i

def refl(b):
    vb = L[b]
    perm = []
    for v in L:
        ip = sum(x * y for x, y in zip(v, vb))   # 4*<v,b>
        assert ip % 4 == 0
        w = tuple(x - (ip // 4) * y for x, y in zip(v, vb))
        perm.append(KEY[w])
    return tuple(perm)

R = [refl(b) for b in range(N)]
ID = tuple(range(N))

def comp(p, q):  # p after q
    return tuple(p[q[i]] for i in range(N))

def closure_np(gens):
    gens = [np.array(g, dtype=np.uint8) for g in gens]
    idn = np.arange(N, dtype=np.uint8)
    seen = {idn.tobytes()}
    allel = [idn]
    frontier = idn[None, :]
    while len(frontier):
        new = []
        for s in gens:
            h = s[frontier]          # s after g, row-wise
            for row in h:
                k = row.tobytes()
                if k not in seen:
                    seen.add(k)
                    new.append(row)
        frontier = np.array(new, dtype=np.uint8) if new else np.zeros((0, N), dtype=np.uint8)
        allel.extend(new)
    return np.array(allel, dtype=np.uint8)

if __name__ == "__main__":
    F0s = set(F0)
    gens = set()
    for f in F0:
        gens.add(R[f])
    for b in range(N):
        for c in range(N):
            if b != c:
                g = comp(R[b], R[c])
                if set(g[i] for i in F0) == F0s:
                    gens.add(g)
    gens.discard(ID)
    gens = sorted(gens)
    print("candidate generators (frame reflections + F0-preserving double reflections):", len(gens))
    # add generators until the closure stops growing over all candidates
    small = [gens[0]]
    el = closure_np(small)
    keys = set(r.tobytes() for r in el)
    for g in gens[1:]:
        if np.array(g, dtype=np.uint8).tobytes() not in keys:
            small.append(g)
            el = closure_np(small)
            keys = set(r.tobytes() for r in el)
    print("generating subset size:", len(small), "group order:", len(el))
    # every candidate generator lies in the group (so the group is generated by all candidates)
    assert all(np.array(g, dtype=np.uint8).tobytes() in keys for g in gens)
    # every element preserves F0 and the Gram matrix up to sign
    for row in el[:: max(1, len(el) // 2000)]:
        assert set(int(row[i]) for i in F0) == F0s
        for a in range(0, N, 7):
            for b in range(N):
                assert abs(GM[row[a]][row[b]]) == abs(GM[a][b])
    # count frames in all 120 lines and the orbit of F0 under all reflections
    onb = [0] * N
    for a in range(N):
        for b in range(N):
            if a != b and GM[a][b] == 0:
                onb[a] |= 1 << b
    frames = []
    def ext(cur_, cand, size):
        if size == 8:
            frames.append(cur_)
            return
        c = cand
        while c:
            bb = c & -c
            i = bb.bit_length() - 1
            c ^= bb
            ext(cur_ | bb, c & onb[i], size + 1)
    for a in range(N):
        ext(1 << a, onb[a] & ~((1 << (a + 1)) - 1), 1)
    print("orthogonal 8-frames among 120 lines:", len(frames))
    f0m = sum(1 << i for i in F0)
    seen = {f0m}
    st = [f0m]
    while st:
        m = st.pop()
        idx = [i for i in range(N) if m >> i & 1]
        for r in R:
            mm = sum(1 << r[i] for i in idx)
            if mm not in seen:
                seen.add(mm)
                st.append(mm)
    print("W(E8)-orbit of F0 among frames:", len(seen))
    print("|W(E8)|/2 / orbit =", 696729600 // 2 // len(seen), " vs order", len(el))
    pickle.dump(small, open("gens_small.pkl", "wb"))
    np.save("group_elems.npy", el)
